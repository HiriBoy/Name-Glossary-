document.getElementById("saveButton").addEventListener("click",()=>{
  const err=document.getElementById("formError");
  const n=document.getElementById("nameInput").value.trim();
  const m=document.getElementById("meaningInput").value.trim();
  const o=document.getElementById("originInput").value.trim()||"Unknown";
  const g=document.getElementById("genderSelect").value;

  let r=document.getElementById("regionSelect").value;
  if(r==="__new"){
    r=document.getElementById("newRegionInput").value.trim();
  }

  if(!n||!m||!r){
    err.textContent="Please fill in name, meaning, and region.";
    err.style.display="block";
    return;
  }

  err.style.display="none";

  added.push({
    id:Date.now()+""+Math.floor(Math.random()*1e4),
    g,r,n,m,o
  });

  save();

  state.gender=g;
  state._rg=g;
  state.region=r;
  state.query="";
  document.getElementById("searchInput").value="";
  resetAddForm();
  render();
});

document.getElementById("mainPanel").addEventListener("click",e=>{
  const editBtn=e.target.closest(".bnr-edit");
  if(editBtn){
    const current=editBtn.dataset.name || "";
    const next=window.prompt("Edit name", current);
    if(next===null) return;
    updateRowName(editBtn.dataset.rowKey, next);
    render();
    return;
  }

  const b=e.target.closest(".bnr-del");
  if(!b)return;

  added=added.filter(a=>a.id!==b.dataset.id);
  save();
  render();
});

