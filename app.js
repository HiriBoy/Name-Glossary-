const LSKEY = "babyNamesRef.v1";
const genders = Object.keys(DATA);
const GSHORT = {
  "Female Names":"Female",
  "Male Names":"Male",
  "Unisex / Gender-Neutral Names":"Unisex"
};

function loadAdded(){
  try {
    const raw = localStorage.getItem(LSKEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed)
      ? parsed.filter(item => item && item.g && item.r && item.n && item.m)
      : [];
  } catch (e) {
    return [];
  }
}

let added = loadAdded();
const state = { gender:"All", region:null, query:"", _rg:null };

function save(){
  try { localStorage.setItem(LSKEY, JSON.stringify(added)); } catch(e){}
}

function esc(s){
  return String(s).replace(/[&<>"']/g,c=>({
    "&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"
  }[c]));
}

function allRegions(g){
  const set=[];
  (g==="All"?genders:[g]).forEach(gg=>{
    Object.keys(DATA[gg]).forEach(r=>{ if(!set.includes(r)) set.push(r); });
  });
  added.forEach(a=>{
    if(a.g===g || g==="All"){
      if(!set.includes(a.r)) set.push(a.r);
    }
  });
  return set;
}

function rowsFor(g,r){
  const base=(DATA[g]&&DATA[g][r])
    ? DATA[g][r].map((x,index)=>({
        n:x[0],
        m:x[1],
        o:x[2],
        mine:false,
        rowKey:`base|${g}|${r}|${index}`
      }))
    : [];
  const extra=added
    .filter(a=>a.g===g&&a.r===r)
    .map(a=>({
      n:a.n,
      m:a.m,
      o:a.o,
      mine:true,
      id:a.id,
      rowKey:`added|${a.id}`
    }));
  return base.concat(extra).sort((a,b)=>
    a.n.localeCompare(b.n,undefined,{numeric:true,sensitivity:"base"})
  );
}

function totalCount(){
  return genders.reduce((s,g)=>
    s+Object.keys(DATA[g]).reduce((t,r)=>t+DATA[g][r].length,0),0
  )+added.length;
}

function countFor(g,r){
  return ((DATA[g]&&DATA[g][r])?DATA[g][r].length:0)
    +added.filter(a=>a.g===g&&a.r===r).length;
}

function renderTabs(){
  const tabs=["All"].concat(genders);
  document.getElementById("tabs").innerHTML=tabs.map(t=>
    `<button class="bnr-tab${state.gender===t?" on":""}" data-g="${esc(t)}">${esc(GSHORT[t]||t)}</button>`
  ).join("");
}

function renderSide(){
  const el=document.getElementById("regionPanel");
  let html="";
  const list=state.gender==="All"?genders:[state.gender];

  list.forEach(g=>{
    html+=`<div class="bnr-glabel">${esc(GSHORT[g])}</div>`;
    Object.keys(DATA[g])
      .concat(allRegions(g).filter(r=>!DATA[g][r]))
      .forEach(r=>{
        const on=state.region===r&&state._rg===g;
        html+=`<button class="bnr-rbtn${on?" on":""}" data-g="${esc(g)}" data-r="${esc(r)}">
          <span>${esc(r)}</span>
          <span class="bnr-count">${countFor(g,r)}</span>
        </button>`;
      });
  });

  el.innerHTML=html;
}

function tableHTML(rows,g,r,showContext){
  const body=rows.map(x=>{
    const edit=`<button class="bnr-edit" data-row-key="${esc(x.rowKey)}" data-name="${esc(x.n)}" aria-label="Edit ${esc(x.n)}">Edit</button>`;
    const del=x.mine
      ? `<button class="bnr-del" data-id="${x.id}" aria-label="Remove ${esc(x.n)}">Remove</button>`
      : "";

    return `<tr class="bnr-row">
      <td class="bnr-nm">${esc(x.n)}${x.mine?'<span class="bnr-badge">yours</span>':""}</td>
      <td>${esc(x.m)}</td>
      <td class="bnr-org">${esc(x.o)}</td>
      <td style="padding:0;border:0;width:120px">
        <div class="bnr-actions">
          ${edit}${del}
        </div>
      </td>
    </tr>`;
  }).join("");

  const ctx=showContext
    ? `<div class="bnr-sectxt">${esc(GSHORT[g])} · ${esc(r)}</div>`
    : "";

  const head=showContext
    ? ""
    : `<div class="bnr-rhead">
        <h2>${esc(r)}</h2>
        <span class="bnr-crumb">${esc(GSHORT[g])} · ${rows.length} name${rows.length===1?"":"s"}</span>
      </div>`;

  return ctx+head+`<div class="bnr-tablewrap">
    <table class="bnr-table">
      <thead>
        <tr>
          <th style="width:190px">Name</th>
          <th>Meaning</th>
          <th style="width:200px">Origin</th>
          <th style="width:120px"></th>
        </tr>
      </thead>
      <tbody>${body}</tbody>
    </table>
  </div>`;
}

function renderMain(){
  const el=document.getElementById("mainPanel");
  const q=state.query.trim().toLowerCase();

  if(q){
    let html="",hits=0;

    genders.forEach(g=>{
      Object.keys(DATA[g])
        .concat(allRegions(g).filter(r=>!DATA[g][r]))
        .forEach(r=>{
          const rows=rowsFor(g,r).filter(x=>
            (x.n+" "+x.m+" "+x.o).toLowerCase().includes(q)
          );

          if(rows.length){
            hits+=rows.length;
            html+=tableHTML(rows,g,r,true);
          }
        });
    });

    el.innerHTML=hits
      ? html
      : `<div class="bnr-empty">No names match "${esc(state.query)}".</div>`;
    return;
  }

  let g=state._rg||(state.gender==="All"?genders[0]:state.gender);
  let r=state.region||Object.keys(DATA[g])[0];

  if(!DATA[g]||!DATA[g][r]){
    g=genders[0];
    r=Object.keys(DATA[g])[0];
  }

  el.innerHTML=tableHTML(rowsFor(g,r),g,r,false);
}

function render(){
  document.getElementById("totalBadge").textContent=totalCount()+" names";
  document.getElementById("statusText").textContent=added.length
    ? 'Names you add are saved in this browser and marked "yours". Hover one to edit or remove it.'
    : "";

  renderTabs();
  renderSide();
  renderMain();
}

function updateRowName(rowKey, newName){
  const trimmed=newName.trim();
  if(!trimmed) return;

  const [kind, ...rest]=rowKey.split("|");

  if(kind==="added"){
    const id=rest.join("|");
    const match=added.findIndex(a=>a.id===id);
    if(match!==-1){
      added[match].n=trimmed;
      save();
    }
    return;
  }

  if(kind==="base"){
    const [g,r,index]=rest;
    const row=DATA[g]&&DATA[g][r]&&DATA[g][r][Number(index)];
    if(row){
      row[0]=trimmed;
    }
  }
}

